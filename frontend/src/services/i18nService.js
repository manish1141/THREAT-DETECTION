export const i18nService = {
  getLanguage() {
    if (typeof window !== 'undefined' && window.localStorage) {
      return window.localStorage.getItem('tg_language') || 'en';
    }
    return 'en';
  },

  setLanguage(lang) {
    if (typeof window !== 'undefined' && window.localStorage) {
      window.localStorage.setItem('tg_language', lang);
    }
  },

  t(key, lang = 'en') {
    return translations[lang]?.[key] || translations['en']?.[key] || key;
  }
};
